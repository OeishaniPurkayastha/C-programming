#include <stdio.h>
int main() {
    int num = 42;
    float pi = 3.14159;
    char letter = 'A';

    // Using format specifiers to print different types of variables
    printf("Integer: %d\n", num);
    printf("Floating point: %.2f\n", pi);
    printf("Character: %c\n", letter);

    return 0;
}